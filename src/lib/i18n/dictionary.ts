export const dictionaries: Record<Locale, Record<DictionaryKey, string>> = { en, th };

export type Vars = Record<string, string | number>;

export function translate(locale: Locale, key: DictionaryKey, vars?: Vars): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

export type Translator = (key: DictionaryKey, vars?: Vars) => string;

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "th";
}
